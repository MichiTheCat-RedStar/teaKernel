; Это 16-битный загрузочный сектор (512 байт), который работает в реальном режиме
; Он просто пишет в 0xB8000 и зависает

org 0x7C00          ; BIOS загружает нас по этому адресу
bits 16             ; 16-битный реальный режим

start:
    ; Очищаем экран (заполняем весь буфер пробелами)
    mov ax, 0xB800
    mov es, ax
    xor di, di
    mov cx, 2000        ; 80*25 = 2000 символов
    mov ax, 0x0720      ; 0x07 = серый фон, 0x20 = пробел
    rep stosw

    ; Пишем "HELLO" в верхний левый угол
    mov word [es:0], 0x0748   ; 'H'
    mov word [es:2], 0x0745   ; 'E'
    mov word [es:4], 0x074C   ; 'L'
    mov word [es:6], 0x074C   ; 'L'
    mov word [es:8], 0x074F   ; 'O'

    ; Бесконечный цикл
    cli
    jmp $

times 510-($-$$) db 0   ; Заполняем нулями до 510-го байта
dw 0xAA55               ; Подпись загрузочного сектора (магическое число)
